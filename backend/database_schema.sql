-- This table connects to the 'Client' table via the id column
CREATE TABLE IF NOT EXISTS public."Client" (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "Username" CHARACTER VARYING NOT NULL,
  "Gmail" CHARACTER VARYING NOT NULL,
  "password" CHARACTER VARYING NOT NULL,
  "Gender" CHARACTER VARYING NULL,
  "Age" SMALLINT NULL,
  "Education" TEXT NULL,
  "Contect_No" TEXT NULL,
  "Experience" SMALLINT NULL,
  "Farm_Area" INTEGER NULL,
  "Farming_Goal" TEXT NULL,
  "Current_Crops" TEXT NULL, -- Suggestion: Stored as comma-separated or JSON string
  "Previous_Data" TEXT NULL, -- Suggestion: Stored as a JSON string for historical records
  "created_at" TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT Client_pkey PRIMARY KEY (id),
  CONSTRAINT Client_gmail_key UNIQUE ("Gmail")
) TABLESPACE pg_default;