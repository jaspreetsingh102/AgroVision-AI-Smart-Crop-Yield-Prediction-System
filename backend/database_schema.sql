-- This table connects to the 'Client' table via the id column
CREATE TABLE IF NOT EXISTS public."Client" (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "Username" CHARACTER VARYING NOT NULL,
  "Gmail" CHARACTER VARYING NOT NULL,
  "password" CHARACTER VARYING NOT NULL,
  "Gender" CHARACTER VARYING NULL,
  "Age" SMALLINT NULL,
  "Education" TEXT NULL,
  "Contect_No" TEXT NULL,
  "Experience" SMALLINT NULL,
  "Farm_Area" INTEGER NULL,
  "Farming_Goal" TEXT NULL,
  "Current_Crops" TEXT NULL, -- Suggestion: Stored as comma-separated or JSON string
  "Previous_Data" TEXT NULL, -- Suggestion: Stored as a JSON string for historical records
  "created_at" TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT Client_pkey PRIMARY KEY (id),
  CONSTRAINT Client_gmail_key UNIQUE ("Gmail")
) TABLESPACE pg_default;

-- Products table for the Market section
CREATE TABLE IF NOT EXISTS public."products" (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  name CHARACTER VARYING NOT NULL,
  category CHARACTER VARYING,
  seller_id uuid REFERENCES public."seller"(seller_id), -- Link product to a seller
  price DECIMAL(10,2),
  unit CHARACTER VARYING, -- e.g., "kg", "bag", "liter"
  description TEXT,
  img_url TEXT,
  stock INTEGER DEFAULT 0,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Orders table
CREATE TABLE IF NOT EXISTS public."orders" (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  buyer_id bigint NOT NULL,
  seller_id uuid NOT NULL, 
  total_amount numeric NOT NULL,
  status text DEFAULT 'pending',
  created_at timestamptz DEFAULT now(),
  CONSTRAINT fk_buyer FOREIGN KEY (buyer_id) REFERENCES public."Client" (id) ON DELETE CASCADE,
  CONSTRAINT fk_seller FOREIGN KEY (seller_id) REFERENCES public."seller" (seller_id) ON DELETE CASCADE
);

-- Order items table
CREATE TABLE IF NOT EXISTS public."order_items" (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL,
  product_id uuid NOT NULL, -- Updated to match products.id (uuid)
  quantity integer NOT NULL,
  price numeric NOT NULL,
  CONSTRAINT fk_order FOREIGN KEY (order_id) REFERENCES public."orders" (id) ON DELETE CASCADE,
  CONSTRAINT fk_product FOREIGN KEY (product_id) REFERENCES public."products" (id) ON DELETE CASCADE
);